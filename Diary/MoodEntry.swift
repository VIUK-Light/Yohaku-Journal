import Foundation
import SwiftData

// @Modelマクロは、このクラスをSwiftDataが管理するデータモデルであることを示します。
// SwiftDataは、このクラスのインスタンスを永続化（データベースに保存・読み込み）する処理を自動的に行います。
@Model
// finalキーワードは、このクラスがこれ以上サブクラス化（継承）されないことを示します。
// これにより、パフォーマンスが向上することがあります。
final class MoodEntry {
    // 各記録を一意に識別するためのユニークID。UUID()で自動的に生成されます。
    var id = UUID()
    // 記録が作成された日時。デフォルトでは現在の日時が設定されます。
    var date = Date()
    // 気分の概要を文字列で保存します（例：「ハッピー」「悲しい」など）。
    var mood = ""
    // 気分を数値で評価したスコア。デフォルト値は3です。
    var moodScore = 3
    // 記録の種類を識別するための文字列（例：「今現在の気分」「1日の振り返り」など）。
    var recordType = "今現在の気分"
    // 感じた具体的な感情を複数保存するための文字列の配列（例：["喜び", "興奮"]）。
    var emotions: [String] = []
    // 自由記述のメモを保存するための文字列。
    var notes = ""
    // その日に行った活動を複数保存するための文字列の配列（例：["仕事", "運動"]）。
    var activities: [String] = []
    // 感謝していることを記述するための文字列。
    var gratitude = ""
    // 1日の振り返りや内省を記述するための文字列。
    var reflections = ""
    // 気分に影響を与えた要因を複数保存するための文字列の配列（例：["天気", "人間関係"]）。
    var influences: [String] = []
    // 生活に関連する要因を複数保存するための文字列の配列（例：["睡眠", "食事"]）。
    var lifeFactors: [String] = []
    
    // SwiftDataモデルには、初期化メソッド（init）が必要です。
    // すべてのプロパティにデフォルト値が設定されているため、空のinitで問題ありません。
    init() {}
}
